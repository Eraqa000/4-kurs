export interface DescribeCheck {
  enough: boolean
  hasPosition: boolean
  hasColor: boolean
}

export function checkDescription(text: string): DescribeCheck {
  const lower = text.toLowerCase()
  const words = lower.split(/\s+/).filter(Boolean)
  const hasPosition = POSITION_STEMS.some((s) => lower.includes(s))
  const hasColor = words.some((w) => COLOR_STEMS.some((s) => w.startsWith(s)))
  return { enough: words.length >= 3, hasPosition, hasColor }
}
