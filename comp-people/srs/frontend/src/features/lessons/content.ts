import type { Lang } from '../../i18n/messages'

/** Текст на двух языках. */
export interface Tr {
  kk: string
  ru: string
}

export interface InfoStep {
  type: 'info'
  text: Tr
}

export interface ChoiceStep {
  type: 'choice'
  prompt: Tr
  options: Tr[]
  /** индекс правильного варианта */
  correct: number
  correctFeedback: Tr
  /** подсказка после первой ошибки */
  hint: Tr
}

/** Свободный ответ: ребёнок описывает словами. Проверяется мягко, ошибкой не считается. */
export interface DescribeStep {
  type: 'describe'
  prompt: Tr
}

export type Step = InfoStep | ChoiceStep | DescribeStep

export interface Lesson {
  id: string
  title: Tr
  /** одна цель урока, озвучивается в начале */
  goal: Tr
  steps: Step[]
}

